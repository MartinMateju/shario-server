const builtInRoleSet = new Set<string>(BUILT_IN_WORKSPACE_ROLES);

export const isBuiltInWorkspaceRole = (
  role: unknown,
): role is BuiltInWorkspaceRole => {
  return typeof role === "string" && builtInRoleSet.has(role);
};

export const isWorkspaceRole = (
  role: unknown,
): role is WorkspaceRole => {
  return role === WORKSPACE_ROLE.CUSTOM || isBuiltInWorkspaceRole(role);
};

export const getBuiltInRolePermissions = (
  role: BuiltInWorkspaceRole,
): readonly WorkspacePermission[] => BUILT_IN_ROLE_CATALOG[role].permissions;

export const listBuiltInRoles = (): BuiltInRoleDefinition[] => {
  return BUILT_IN_WORKSPACE_ROLES.map((role) => ({
    key: role,
    name: BUILT_IN_ROLE_NAMES[role],
    permissions: [...getBuiltInRolePermissions(role)],
  }));
};

export const getBuiltInRoleName = (
  role: BuiltInWorkspaceRole,
): string => BUILT_IN_ROLE_NAMES[role];
