const viewerPermissions = ALL_WORKSPACE_PERMISSIONS.filter(
  (permission) =>
    (permission.endsWith(".view") || permission === WORKSPACE_PERMISSION.TEAM_VIEW) &&
    permission !== WORKSPACE_PERMISSION.COMMUNICATIONS_AUDIT_VIEW &&
    permission !== WORKSPACE_PERMISSION.AI_AUDIT_VIEW &&
    permission !== WORKSPACE_PERMISSION.ACCESS_CODES_VIEW &&
    permission !== WORKSPACE_PERMISSION.ACCESS_CODES_AUDIT_VIEW &&
    permission !== WORKSPACE_PERMISSION.PLANNING_TEAM_VIEW,
);

